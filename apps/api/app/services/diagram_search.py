# File: app/services/diagram_search.py
"""
Diagram search service for fetching lecture-relevant diagrams.

Searches Wikimedia Commons using structured, lecture-grounded queries
generated by the LLM.  Returns ranked, filtered results that are
relevant to the actual lecture content.

Design decisions:
  1. Queries come from the LLM (not from naive word-length heuristics).
  2. Multiple queries per diagram concept are tried for recall.
  3. Results are filtered to exclude irrelevant images (logos, flags, etc.).
  4. SVG and PNG are preferred over photographs.
  5. All searches are run in parallel for speed.
"""
import asyncio
import re
from typing import List, Dict, Any, Optional
import httpx

from app.core.logger import get_logger

logger = get_logger("TAP.DiagramSearch")

WIKIMEDIA_API_URL = "https://commons.wikimedia.org/w/api.php"

# File extensions to accept (educational diagrams)
ALLOWED_EXTENSIONS = {"svg", "png", "jpg", "jpeg", "gif", "webp"}

# Filename patterns that indicate non-diagram images (logos, flags, portraits, etc.)
EXCLUDE_PATTERNS = re.compile(
    r"\b("
    r"logo|icon|flag|coat\s*of\s*arms|emblem|seal|badge|avatar"
    r"|portrait|photo|headshot|face|selfie"
    r"|screenshot|stub|ambox|question\s*book|edit-clear"
    r"|commons-|wiki-|crystal-|nuvola|tango-"
    r"|medal|trophy|award|ribbon"
    r")\b",
    re.IGNORECASE,
)

# Maximum number of results per query
MAX_PER_QUERY = 6
# Maximum total results across all queries for a single diagram
MAX_TOTAL = 8


async def search_wikimedia_diagrams(
    query: str,
    n_results: int = MAX_PER_QUERY,
) -> List[Dict[str, Any]]:
    """
    Search Wikimedia Commons for diagram images matching a query.

    Args:
        query: A specific, technical search query (e.g. "TCP/IP protocol stack diagram")
        n_results: Maximum number of results to return

    Returns:
        List of dicts with url, thumb, title, sourceUrl, width, height
    """
    results: List[Dict[str, Any]] = []

    try:
        headers = {
            "User-Agent": (
                "TAP-EducationPlatform/1.0 "
                "(https://github.com/TAP-Education; tap.education.platform@gmail.com) "
                "python-httpx"
            ),
            "Accept": "application/json",
        }

        params = {
            "action": "query",
            "format": "json",
            "origin": "*",
            "generator": "search",
            "gsrsearch": f"{query} filetype:bitmap|drawing",
            "gsrnamespace": "6",  # File namespace
            "gsrlimit": str(min(n_results * 2, 20)),  # Fetch extra to filter
            "prop": "imageinfo",
            "iiprop": "url|size|mime|extmetadata",
            "iiurlwidth": "500",
        }

        async with httpx.AsyncClient(timeout=12.0, headers=headers) as client:
            resp = await client.get(WIKIMEDIA_API_URL, params=params)

            if resp.status_code != 200:
                logger.warning(
                    f"Wikimedia search HTTP {resp.status_code} for '{query}'"
                )
                return results

            data = resp.json()
            pages = data.get("query", {}).get("pages", {})

            if not pages:
                logger.info(f"Wikimedia: no results for '{query}'")
                return results

            for page in pages.values():
                ii = page.get("imageinfo", [{}])[0]
                if not ii:
                    continue

                url = ii.get("url", "")
                thumb_url = ii.get("thumburl", "")
                mime = ii.get("mime", "")
                width = ii.get("width", 0)
                height = ii.get("height", 0)

                # Extract file extension
                ext = url.rsplit(".", 1)[-1].lower() if "." in url else ""

                # Filter: only allowed image types
                if ext not in ALLOWED_EXTENSIONS:
                    continue

                # Filter: require thumbnail
                if not thumb_url:
                    continue

                # Filter: exclude very small images (likely icons)
                if width < 150 or height < 100:
                    continue

                # Filter: exclude known non-diagram patterns
                raw_title = page.get("title", "")
                clean_title = raw_title.replace("File:", "")
                clean_title = re.sub(r"\.[a-zA-Z]+$", "", clean_title)

                if EXCLUDE_PATTERNS.search(clean_title) or EXCLUDE_PATTERNS.search(url):
                    continue

                # Build source URL
                source_url = (
                    f"https://commons.wikimedia.org/wiki/"
                    f"{raw_title.replace(' ', '_')}"
                )

                # Extract description from metadata if available
                desc = ""
                extmeta = ii.get("extmetadata", {})
                if extmeta:
                    desc_data = extmeta.get("ImageDescription", {})
                    desc = desc_data.get("value", "")
                    # Strip HTML tags from description
                    if desc:
                        desc = re.sub(r"<[^>]+>", "", desc).strip()
                        if len(desc) > 200:
                            desc = desc[:200] + "..."

                results.append({
                    "url": url,
                    "thumb": thumb_url,
                    "title": clean_title,
                    "sourceUrl": source_url,
                    "width": width,
                    "height": height,
                    "format": ext.upper(),
                    "description": desc,
                })

                if len(results) >= n_results:
                    break

        logger.info(
            f"Wikimedia: {len(results)} diagrams found for '{query}'"
        )

    except Exception as e:
        logger.warning(f"Wikimedia diagram search failed for '{query}': {e}")

    return results


def _rank_results(
    results: List[Dict[str, Any]],
    query_terms: List[str],
) -> List[Dict[str, Any]]:
    """
    Rank diagram results by relevance.

    Scoring:
      - SVG format preferred (educational diagrams are often SVG)
      - Title word overlap with search query
      - Larger images preferred over tiny ones
      - PNG preferred over JPG (sharper for diagrams)
    """
    def score(item: Dict[str, Any]) -> float:
        s = 0.0
        fmt = item.get("format", "").lower()
        title_lower = item.get("title", "").lower()
        desc_lower = item.get("description", "").lower()

        # Format bonus
        if fmt == "svg":
            s += 3.0
        elif fmt == "png":
            s += 2.0
        elif fmt in ("jpg", "jpeg"):
            s += 1.0

        # Title match bonus
        for term in query_terms:
            term_lower = term.lower()
            if term_lower in title_lower:
                s += 2.0
            elif term_lower in desc_lower:
                s += 1.0

        # Size bonus (prefer reasonable size, not massive)
        w = item.get("width", 0)
        if 300 <= w <= 2000:
            s += 1.0
        elif w > 2000:
            s += 0.5

        # Keyword indicators (diagram-related words in title)
        diagram_words = [
            "diagram", "schematic", "architecture", "flowchart",
            "block diagram", "circuit", "structure", "model",
            "overview", "hierarchy", "topology", "layout", "process",
        ]
        for word in diagram_words:
            if word in title_lower:
                s += 1.5
                break

        return s

    # Extract query terms for matching
    terms = []
    for q in query_terms:
        terms.extend(q.split())
    terms = [t for t in terms if len(t) > 2]

    results.sort(key=lambda x: score(x), reverse=True)
    return results


async def fetch_diagrams_for_lecture(
    diagram_specs: List[Dict[str, Any]],
    max_diagrams: int = 4,
) -> List[Dict[str, Any]]:
    """
    Fetch diagrams for a lecture based on structured diagram specs from the LLM.

    Each diagram spec should contain:
      - title: What the diagram represents
      - search_queries: List of search queries to try
      - description: Why this diagram is relevant
      - relevance: Which section it relates to

    Args:
        diagram_specs: List of diagram specifications from LLM
        max_diagrams: Maximum number of diagrams to return total

    Returns:
        List of diagram results with metadata
    """
    if not diagram_specs:
        logger.info("No diagram specs provided, skipping search")
        return []

    logger.info(
        f"Fetching diagrams for {len(diagram_specs)} concepts "
        f"(max {max_diagrams} total)"
    )

    all_diagrams: List[Dict[str, Any]] = []
    seen_urls: set = set()

    # Process each diagram spec (limit to avoid too many API calls)
    specs_to_process = diagram_specs[:max_diagrams]

    for spec in specs_to_process:
        title = spec.get("title", "")
        search_queries = spec.get("search_queries", [])
        description = spec.get("description", "")
        relevance = spec.get("relevance", "")

        if not search_queries:
            # Fallback: use the title as the query
            search_queries = [f"{title} diagram"]

        # Search with each query in parallel
        search_tasks = [
            search_wikimedia_diagrams(query=q, n_results=4)
            for q in search_queries[:3]  # Max 3 queries per concept
        ]

        query_results = await asyncio.gather(*search_tasks, return_exceptions=True)

        # Merge and deduplicate results
        concept_results: List[Dict[str, Any]] = []
        for result_set in query_results:
            if isinstance(result_set, Exception):
                logger.warning(f"Diagram query failed: {result_set}")
                continue
            for r in result_set:
                if r["url"] not in seen_urls:
                    seen_urls.add(r["url"])
                    concept_results.append(r)

        # Rank results
        all_query_terms = search_queries
        concept_results = _rank_results(concept_results, all_query_terms)

        # Take best results for this concept
        best = concept_results[:3]

        if best:
            all_diagrams.append({
                "concept_title": title,
                "description": description,
                "relevance": relevance,
                "search_queries_used": search_queries[:3],
                "results": best,
                "total_found": len(concept_results),
            })
            logger.info(
                f"Diagram '{title}': {len(best)} results "
                f"(from {len(concept_results)} total)"
            )
        else:
            logger.info(f"Diagram '{title}': no results found")
            all_diagrams.append({
                "concept_title": title,
                "description": description,
                "relevance": relevance,
                "search_queries_used": search_queries[:3],
                "results": [],
                "total_found": 0,
            })

    logger.info(
        f"Diagram search complete: "
        f"{sum(len(d['results']) for d in all_diagrams)} total results "
        f"across {len(all_diagrams)} concepts"
    )

    return all_diagrams
